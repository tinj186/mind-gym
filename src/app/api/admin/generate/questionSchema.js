import { z } from 'zod';

export const UniversalQuestionSchema = z.object({
  // 1. META: Tags and Routing data
  meta: z.object({
    level: z.string(),
    topic: z.string(),
    type: z.enum(['SHORT_QUESTION', 'STRUCTURED', 'MCQ']),
    difficulty: z.enum(['Foundation', 'Standard', 'Advanced']),
  }),

  // 2. CONTENT: What the student reads and solves
  content: z.object({
    questionText: z.union([z.string(), z.array(z.string())]),
    options: z.array(z.string()).nullable().optional(),
    finalAnswer: z.string(),
    acceptedAnswers: z.array(z.string()).optional(),
    solutionSteps: z.union([z.string(), z.array(z.string())]),
    hint: z.string().optional(),
    defectMap: z.record(z.string()).optional().nullable(),
  }),

  // 3. VISUAL ENGINE: The Polymorphic Payload
  visualEngine: z.object({
    componentToRender: z.enum([
      'COUNTING_OBJECTS',
      'OBJECT_COUNTING',
      'ICON_GRID',
      'RENDER_ICON_GRID',
      'TWO_SET_COMPARISON',
      'NUMBER_CARDS',
      'SINGAPORE_MONEY',
      'NUMBER_PATTERN',
      'EQUAL_GROUPS',
      'GROUPING_WORKSPACE',
      'ORDINAL_LINE',
      'BASE_TEN_BLOCKS',
      'NUMBER_BOND',
      'FACT_TRIANGLE',
      'FACTOR_RAINBOW',
      'FACTOR_RAINBOW_VISUALIZER',
      'VENN_DIAGRAM',
      'VENN_DIAGRAM_VISUALIZER',
      'REPEATING_PATTERN',
      'REPEATING_PATTERN_VISUALIZER',
      'GRID_ARRAY',
      'GRID_ARRAY_VISUALIZER',
      'INTERACTIVE_SCRIBBLE_CANVAS',
      'SCRIBBLE_CANVAS',
      'SHAPE',
      'SHAPE_3D',
      'SHAPE_3D_PATTERN',
      'COMPOSITE_SHAPE_3D',
      'SHAPE_DISPLAY',
      'GRID_DISPLAY',
      'GRID_DRAWING_CANVAS',
      'PICTURE_GRAPH_DISPLAY',
      'CROSS_OUT_GROUP',
      'TF_MATRIX_TABLE',
      'MEASUREMENT_UNIT',
      'CLOCK_DISPLAY',
      'MULTI_COMPONENT',
      'FRACTION_DISPLAY',
      'FRACTION_PIZZA_VISUALIZER',
      'FRACTION_BAR_VISUALIZER',
      'BAR_MODEL',
      'VERTICAL_ALGORITHM',
      'VERTICAL_ALGORITHM_GRID',
      'AREA_MODEL_MULTIPLICATION',
      'AREA_MODEL_DIVISION',
      'LONG_DIVISION',
      'LONG_DIVISION_GRID',
      'DIAGRAM_RENDERER',
      'FRACTION_EQUIVALENCE',
      'HTML_CONTENT',
      'STATIC_IMAGE',
      'VOLUME_BEAKER',
      'MEASUREMENT_RULER',
      'MASS_SCALE',
      'TIMETABLE',
      'TIMELINE',
      'SQUARE_GRID_SHAPE',
      'GEOMETRY_POLYGON',
      'ANGLE_VISUALIZER',
      'AREA_PERIMETER_EXPLORER',
      'LINE_AND_POLYGON',
      'BAR_GRAPH',
      'BAR_GRAPH_VISUALIZER',
      'PLACE_VALUE_CHART',
      'NUMBER_LINE',
      'NUMBER_LINE_ADVANCED',
      'NUMBER_SEQUENCE_BLOCKS',
      'TABLE_PATTERN_VISUALIZER',
      'BAR_MODEL_COMPARISON',
      'DIGIT_CARD_SORTER',
      'NONE',
    ]), // Registered native visual engines
    componentData: z.record(z.any()).nullable().optional(),
  }).passthrough(),

  // 4. INPUT REQUIREMENT: How the student answers
  inputRequirement: z.object({
    inputType: z.enum([
      'STANDARD_TEXT',
      'MCQ_BUTTONS',
      'MATH_KEYBOARD',
      'FRACTION_PAD',
      'MULTI_STEP_INPUT',
      'INTERACTIVE_GRID',
      'INTERACTIVE_BAR_BUILDER'
    ]).default('STANDARD_TEXT'),
    steps: z.array(z.object({
      label: z.string(),
      expectedAnswer: z.string().optional(),
      expected: z.string().optional(),
      acceptedAnswers: z.array(z.string()).optional(),
      defectMap: z.record(z.string()).optional().nullable()
    }).passthrough()).optional(),
    barBuilderConfig: z.record(z.any()).optional()
  }).passthrough().nullable().optional()
});