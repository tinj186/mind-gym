export function getThemeForLevel(level = '') {
  const normalizedLevel = level.toLowerCase();
  
  if (normalizedLevel.includes('primary 1')) return LEVEL_THEMES.p1;
  if (normalizedLevel.includes('primary 2')) return LEVEL_THEMES.p2;
  if (normalizedLevel.includes('primary 3')) return LEVEL_THEMES.p3;
  if (normalizedLevel.includes('primary 4')) return LEVEL_THEMES.p4;
  if (normalizedLevel.includes('primary 5')) return LEVEL_THEMES.p5;
  if (normalizedLevel.includes('primary 6')) return LEVEL_THEMES.p6;
  
  // Default fallback
  return LEVEL_THEMES.p1;
}

export function getDailyTargetReps(level = '') {
  const normalizedLevel = level.toLowerCase();
  if (normalizedLevel.includes('primary 1') || normalizedLevel.includes('primary 2')) return 10;
  if (normalizedLevel.includes('primary 3') || normalizedLevel.includes('primary 4')) return 15;
  if (normalizedLevel.includes('primary 5') || normalizedLevel.includes('primary 6')) return 20;
  return 10;
}

